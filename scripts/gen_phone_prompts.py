#!/usr/bin/env python3
"""Writes watch/AudayPhone/PipelinePrompts.swift from app/auday_mode.py, so the iPhone's AI
pipeline sends exactly the prompts the Mac does. Run after changing a prompt in auday_mode.py:

  .venv/bin/python scripts/gen_phone_prompts.py

tests/test_phone_prompts.py fails while the Swift file is out of date.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app import auday_mode  # noqa: E402

TARGET = ROOT / "watch" / "AudayPhone" / "PipelinePrompts.swift"
CONSTANTS = [("dataRules", "DATA_RULES"), ("mixedRule", "MIXED_RULE"), ("summaryTask", "SUMMARY_TASK"),
             ("highlightTask", "HIGHLIGHT_TASK"), ("interpretTask", "INTERPRET_TASK"),
             ("overviewTask", "OVERVIEW_TASK"), ("reflectionTask", "REFLECTION_TASK"), ("reviewTask", "REVIEW_TASK")]


def swift_string(text):
    # A raw multi-line literal: no escaping, the content starts and ends on its own lines.
    assert '"""#' not in text
    return '#"""\n' + "\n".join("    " + line if line else "" for line in text.split("\n")) + '\n    """#'


def render():
    out = ["// Generated by scripts/gen_phone_prompts.py from app/auday_mode.py. Do not edit by hand.",
           "",
           "/// The prompts of Auday's hourly and daily pipeline, word for word as the Mac sends them.",
           "enum PipelinePrompts {"]
    for name, constant in CONSTANTS:
        out.append(f"    static let {name} = {swift_string(getattr(auday_mode, constant))}")
        out.append("")
    out.append("    /// <final_task> wording per call.")
    out.append("    static let final: [String: String] = [")
    for key, value in auday_mode.FINAL.items():
        out.append(f'        "{key}": #"{value}"#,')
    out.append("    ]")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render())
    print(f"wrote {TARGET.relative_to(ROOT)}")
